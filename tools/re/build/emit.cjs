// Stable writer for the generated JS data modules and JSON files (PLAN §5.1, §5.3).
//   module(path, globalCall, obj, opts) -> writes `<globalCall> <json>);` with sorted keys, floats fixed to
//                                          4 decimals, LF line ends, no timestamps
//   json(path, obj, opts)               -> pretty JSON (2 spaces), sorted keys, LF
//   stringify(obj, {indent})            -> the same text without writing
//   stable(obj)                         -> the canonical copy (sorted keys, fixed floats, typed arrays -> arrays)
//   load(path)                          -> evaluates a generated module (or any window.X = … script) in a
//                                          sandbox and returns its window object (used by `check`)
// Key order: integer-like keys ascending, then the other keys by code unit. Arrays keep their order.
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');

const ENVELOPE = "window.SPRITE_DATA = window.SPRITE_DATA || { families:{}, add(name, fam){ this.families[name]=fam; } };\n";
const PRECISION = 4;

function fixNumber(v) {
  if (!Number.isFinite(v)) throw new Error(`emit: non-finite number ${v}`);
  if (Number.isInteger(v)) return v === 0 ? 0 : v;           // -0 -> 0
  const r = Number(v.toFixed(PRECISION));
  return r === 0 ? 0 : r;
}
function keyCompare(a, b) {
  const ia = /^(0|[1-9]\d*)$/.test(a), ib = /^(0|[1-9]\d*)$/.test(b);
  if (ia && ib) return Number(a) - Number(b);
  if (ia !== ib) return ia ? -1 : 1;
  return a < b ? -1 : a > b ? 1 : 0;
}
function stable(v) {
  if (v === null || v === undefined) return null;
  if (typeof v === 'number') return fixNumber(v);
  if (typeof v === 'string' || typeof v === 'boolean') return v;
  if (typeof v === 'bigint') throw new Error('emit: bigint is not serialisable');
  if (ArrayBuffer.isView(v)) return Array.from(v, fixNumber);
  if (Array.isArray(v)) return v.map(x => (x === undefined ? null : stable(x)));
  if (v instanceof Map) v = Object.fromEntries(v);
  if (typeof v === 'object') {
    const out = {};
    for (const k of Object.keys(v).sort(keyCompare)) { const x = v[k]; if (x === undefined || typeof x === 'function') continue; out[k] = stable(x); }
    return out;
  }
  throw new Error(`emit: cannot serialise a ${typeof v}`);
}
function stringify(obj, { indent = 0 } = {}) {
  return JSON.stringify(stable(obj), null, indent || undefined);
}
// Compact JSON with each top-level key on its own line: diff-friendly, and the data URLs stay single lines.
function stringifyModule(obj) {
  const s = stable(obj);
  if (!s || typeof s !== 'object' || Array.isArray(s)) return JSON.stringify(s);
  const keys = Object.keys(s);
  if (!keys.length) return '{}';
  return '{\n' + keys.map(k => `  ${JSON.stringify(k)}:${JSON.stringify(s[k])}`).join(',\n') + '\n}';
}

function writeText(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old !== text) fs.writeFileSync(file, text, 'utf8');
  return old !== text;
}

// globalCall ends with "(" or "," (a call to close with ");"), or with "=" (an assignment to close with ";").
function renderModule(globalCall, obj, { header = null, envelope = null } = {}) {
  const call = globalCall.trim();
  const close = /[(,]$/.test(call) ? ');' : ';';
  const env = envelope == null ? /SPRITE_DATA\.add\s*\(/.test(call) : envelope;
  const lines = [header == null ? '// Generated by tools/re/build-game-assets.cjs from the ROM extracts; do not edit by hand.' : header];
  if (env) lines.push(ENVELOPE.trimEnd());
  lines.push(`${call}${/[(]$/.test(call) ? '' : ' '}${stringifyModule(obj)}${close}`);
  return lines.filter(l => l !== '').join('\n') + '\n';
}
function module_(file, globalCall, obj, opts) {
  const text = renderModule(globalCall, obj, opts || {});
  const changed = writeText(file, text);
  return { file, bytes: Buffer.byteLength(text), changed };
}
function json(file, obj, { indent = 2 } = {}) {
  const text = stringify(obj, { indent }) + '\n';
  const changed = writeText(file, text);
  return { file, bytes: Buffer.byteLength(text), changed };
}

// Runs a browser-style data script in a sandbox: `window.X = …`, bare `X` and the SPRITE_DATA envelope all work.
function load(file, sandbox = null) {
  const win = sandbox || {};
  win.window = win; win.self = win; win.globalThis = win;
  const ctx = vm.createContext(win);
  vm.runInContext(fs.readFileSync(file, 'utf8'), ctx, { filename: file, timeout: 60000 });
  return win;
}

module.exports = { module: module_, json, stringify, stringifyModule, stable, renderModule, load, writeText, ENVELOPE, PRECISION, keyCompare };
