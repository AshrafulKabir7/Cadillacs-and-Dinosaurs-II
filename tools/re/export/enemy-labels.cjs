// Curated animation labels for the enemy export (tools/re/export/enemies.cjs). Research only.
// Keys: type id -> set kind ('main' = the +0x40 set, 'held' = reaction set from 0x2E724, 'down' = reaction set from
// 0x2E68C) -> animation index -> label; 'variant' -> {variantId: {main: {...}}} overrides one variant.
// The suffix says how a label was decided:
//   (live)  the animation played live in that context in the en-* captures (enemy state bytes +0x05/+0x06, P1 state,
//           bot phase, the P1 HP write tap for attacks); the attack id / damage is in <type>.json -> variants[].attacks
//   (sheet) read from the decoded frames on the contact sheet only; the animation was not seen live
// Variants of one type share the layout of their main set (same anim index = same move; checked by comparing frame
// counts and timings, only speeds differ), so labels are per type.
